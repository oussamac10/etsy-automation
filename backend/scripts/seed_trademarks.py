async def seed_database(db_url: str | None = None) -> None:
    if not db_url:
        db_url = os.getenv("DATABASE_URL")
    if not db_url:
        try:
            from app.settings import get_settings
            settings = get_settings()
            db_url = settings.database_url
        except Exception:
            db_url = "postgresql+asyncpg://etsy:etsy_local_password@localhost:55432/etsy_automation"

    print(f"Connecting to database: {db_url.split('@')[-1] if '@' in db_url else db_url}")
    engine = create_async_engine(db_url, echo=False)
    session_factory = async_sessionmaker(engine, expire_on_commit=False)

    async with session_factory() as session:
        repo = SqlTrademarkRepository(session)
        count = await repo.bulk_upsert(INITIAL_TRADEMARK_RECORDS)
        await session.commit()
        print(f"✅ Successfully seeded {count} official USPTO trademark records into PostgreSQL database.")

    await engine.dispose()


if __name__ == "__main__":
    url_arg = sys.argv[1] if len(sys.argv) > 1 else None
    asyncio.run(seed_database(url_arg))
